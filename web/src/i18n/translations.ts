/**
 * Look up translation for key in given language with fallback to English
 */
export function getTranslation(key: string, lang: string = 'en', fallback?: string): string {
  const item = TRANSLATIONS[key];
  if (!item) return fallback || key;
  return item[lang] || item['en'] || fallback || key;
}
