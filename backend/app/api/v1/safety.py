@router.get("/hazards", response_model=ApiResponse[List[LocalizedSafetyGuide]])
async def get_safety_hazards(
    language: str = Query(default="en", description="Target ISO language code"),
    category: Optional[str] = Query(default=None)
):
    lang = language.lower() if language else "en"
    results = []
    for item in CANONICAL_HAZARDS:
        if category and category.lower() != "all" and item["category"] != category.lower():
            continue
        trans = item.get("translations", {}).get(lang) or item.get("translations", {}).get("en") or {}
        results.append(LocalizedSafetyGuide(
            id=item["id"],
            category=item["category"],
            badge_color=item["badge_color"],
            image_url=item["image_url"],
            authority=item["authority"],
            video_url=item["video_url"],
            video_button_label=trans.get("video_button_label", "Watch Safety Video"),
            name=trans.get("name", item["id"].title()),
            title=trans.get("title", trans.get("name", item["id"].title())),
            short_name=trans.get("short_name", item["id"].title()),
            tagline=trans.get("tagline", ""),
            dos=trans.get("dos", []),
            donts=trans.get("donts", []),
            warnings=trans.get("warnings", [])
        ))
    return ApiResponse(success=True, data=results, freshness=FreshnessMetadata(status="fresh", age_seconds=0))

@router.get("/hazards/{hazard_id}", response_model=ApiResponse[LocalizedSafetyGuide])
async def get_safety_hazard_by_id(
    hazard_id: str,
    language: str = Query(default="en")
):
    lang = language.lower() if language else "en"
    for item in CANONICAL_HAZARDS:
        if item["id"].lower() == hazard_id.lower() or item["category"].lower() == hazard_id.lower():
            trans = item.get("translations", {}).get(lang) or item.get("translations", {}).get("en") or {}
            guide = LocalizedSafetyGuide(
                id=item["id"],
                category=item["category"],
                badge_color=item["badge_color"],
                image_url=item["image_url"],
                authority=item["authority"],
                video_url=item["video_url"],
                video_button_label=trans.get("video_button_label", "Watch Safety Video"),
                name=trans.get("name", item["id"].title()),
                title=trans.get("title", trans.get("name", item["id"].title())),
                short_name=trans.get("short_name", item["id"].title()),
                tagline=trans.get("tagline", ""),
                dos=trans.get("dos", []),
                donts=trans.get("donts", []),
                warnings=trans.get("warnings", [])
            )
            return ApiResponse(success=True, data=guide, freshness=FreshnessMetadata(status="fresh", age_seconds=0))
    raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail=f"Safety hazard '{hazard_id}' not found.")